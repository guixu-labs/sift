def test_runner_run_passes_source_through(tmp_path, monkeypatch):
    """run() 的 per-probe dict 透传 source(trigger 命令据此填 ProbeResult)。"""

    from sift.execution.trigger_runner import TriggerRunner
    from sift.models.eval_models import TriggerProbe
    from sift.models.execution_models import RunOutput

    def fake_run_trigger(self, prompt, cwd, env, options: ExecutionOptions = ExecutionOptions(), **kw):
        return RunOutput(exit_code=0, stdout='{"type":"result","result":"x"}')

    monkeypatch.setattr(("sift.execution.trigger_runner.ClaudeRunner.run_trigger"), fake_run_trigger)
    d = _skill_dir(tmp_path)
    tr = TriggerRunner(d, runs=1)
    res = tr.run(
        [
            TriggerProbe(id=1, prompt="q1", expect_trigger=True),
            TriggerProbe(id=2, prompt="q2", expect_trigger=False, source="trace-mined"),
        ],
        out_base=tmp_path / "out",
    )
    assert [p["source"] for p in res["probes"]] == ["generated", "trace-mined"]


