def _verdicts_json(*items):
    return json.dumps({"verdicts": [{"index": i, "verdict": v, "reason": r} for i, v, r in items]})


def test_filter_near_miss_collects_and_drops():
    calls = []

    def llm(prompt):
        calls.append(prompt)
        return _verdicts_json(
            (1, "near_miss", "same domain: error logs"),
            (2, "unrelated", "meeting notes, not log analysis"),
        )

    out = filter_near_miss(["分析下这段日志的报错", "整理会议纪要"], "analyzes error logs", llm)
    assert out == [
        ("near_miss", "same domain: error logs"),
        ("unrelated", "meeting notes, not log analysis"),
    ]
    assert len(calls) == 1
    # 注意力安全 a:只喂 description,不喂 skill 正文 —— prompt 里没有正文(此测 description 即全文)
    assert "analyzes error logs" in calls[0]


def test_filter_near_miss_llm_failure_marks_unverified():
    def llm(prompt):
        raise RuntimeError("claude CLI failed")

    out = filter_near_miss(["query one", "query two"], "desc", llm)
    assert [v for v, _ in out] == ["unverified", "unverified"]
    assert all("LLM 过滤失败" in r for _, r in out)


def test_filter_near_miss_missing_entry_is_unverified():
    def llm(prompt):
        return _verdicts_json((2, "near_miss", "only second judged"))  # index 1 缺失

    out = filter_near_miss(["first", "second"], "desc", llm)
    assert out[0][0] == "unverified"
    assert out[1] == ("near_miss", "only second judged")


def test_filter_near_miss_invalid_verdict_value_dropped_to_unverified():
    def llm(prompt):
        return _verdicts_json((1, "maybe", "bogus"), (2, "near_miss", "ok"))

    out = filter_near_miss(["first", "second"], "desc", llm)
    assert out[0][0] == "unverified"
    assert out[1][0] == "near_miss"


def test_filter_near_miss_two_stage_parse():
    """响应带包装文本时正则抽 {...}(同 _parse_trigger_response)。"""

    def llm(prompt):
        return "Here you go:\n" + _verdicts_json((1, "near_miss", "r")) + "\ndone"

    out = filter_near_miss(["only one"], "desc", llm)
    assert out == [("near_miss", "r")]


def test_filter_near_miss_non_dict_json_marks_unverified():
    """响应是合法 JSON 但非对象(裸数组)→ 该批全 unverified,不炸穿调用方。

    回归钉:json.loads 成功 + 非 dict 时 data.get 会 AttributeError,而
    filter_near_miss 只捕 RuntimeError(LLM 失败约定)、init 顶层只捕 SiftError。
    """
    out = filter_near_miss(["甲条候选", "乙条候选"], "desc", lambda p: '["a", "b"]')
    assert [v for v, _ in out] == ["unverified", "unverified"]


def test_filter_near_miss_non_dict_items_mark_unverified():
    """verdicts 数组里的条目不是对象(裸字符串/数字)→ 该条跳过,不炸穿调用方。

    data 层非 dict 守卫的 item 层对位:item.get 对 str 抛 AttributeError,穿透
    同一条只捕 RuntimeError 的链。docstring 承诺「畸形条目跳过不影响其余」。
    """
    resp = '{"verdicts": ["near_miss", {"index": 2, "verdict": "near_miss", "reason": "ok"}]}'
    out = filter_near_miss(["甲条候选", "乙条候选"], "desc", lambda p: resp)
    assert out[0] == ("unverified", "LLM 过滤失败或该条缺失,仅事实层(未触发)成立")
    assert out[1] == ("near_miss", "ok")


def test_filter_near_miss_non_list_verdicts_marks_unverified():
    """verdicts 键在但值非数组(裸 int/bool)→ 整批 unverified,不 TypeError。

    for 取迭代器这步就抛,循环体内的 item 守卫救不到——解析失败形态的第三层
    (data 非 dict → item 非 dict → verdicts 非数组)。
    """
    for bad in ('{"verdicts": 5}', '{"verdicts": true}', '{"nope": 1}'):
        out = filter_near_miss(["甲条候选"], "desc", lambda p, b=bad: b)
        assert out == [("unverified", "LLM 过滤失败或该条缺失,仅事实层(未触发)成立")]


def test_filter_near_miss_batches_beyond_limit():
    """> NEAR_MISS_BATCH 候选 → 分多批调用(注意力安全 b)。"""
    calls = []

    def llm(prompt):
        calls.append(prompt)
        # 每批只判 index 1(该批第一条)→ 批内其余 unverified,验对齐
        return json.dumps({"verdicts": [{"index": 1, "verdict": "near_miss", "reason": "r"}]})

    candidates = [f"候选请求编号 {i:02d},足够长" for i in range(NEAR_MISS_BATCH + 3)]
    out = filter_near_miss(candidates, "desc", llm)
    assert len(calls) == 2
    # 批内划分:第一批 10 条、第二批 3 条;每批只有第一条(index 1)被判 near_miss,
    # 批内其余 missing → unverified(按批内 index 对齐,不跨批)
    assert out[0][0] == "near_miss"
    assert all(v == "unverified" for v, _ in out[1:NEAR_MISS_BATCH])
    assert out[NEAR_MISS_BATCH][0] == "near_miss"
    assert out[NEAR_MISS_BATCH + 1][0] == "unverified"
    assert out[NEAR_MISS_BATCH + 2][0] == "unverified"
    # prompt 只含本批 queries
    assert candidates[0] in calls[0] and candidates[NEAR_MISS_BATCH - 1] in calls[0]
    assert candidates[NEAR_MISS_BATCH] not in calls[0] and candidates[NEAR_MISS_BATCH] in calls[1]


