def _skill_dir(tmp_path, name="my-skill", description=("analyzes error logs and reports root causes")):
    d = tmp_path / name
    d.mkdir()
    (d / "SKILL.md").write_text(
        (f"---\nname: {name}\ndescription: {description}\n---\n# Body\nsecret instructions\n"), encoding="utf-8"
    )
    return d


def test_mine_trigger_probes_end_to_end(tmp_path, monkeypatch):
    """near_miss 收为 trace-mined should-not 探题;unrelated 丢;attention:prompt 不含正文。"""
    from sift.evals.generator import EvalInitGenerator

    name, _ = _skill()
    tp = _write(
        tmp_path,
        [
            _user("帮我把崩溃日志的根因找出来"),  # near_miss → 收
            _user("帮我订一张机票"),  # unrelated → 丢
        ],
        name="session.jsonl",
    )
    prompts = []

    def fake_llm(prompt, *a, **k):
        prompts.append(prompt)
        return _verdicts_json((1, "near_miss", "log domain"), (2, "unrelated", "travel"))

    monkeypatch.setattr("sift.evals.generator.call_claude", fake_llm)
    probes = EvalInitGenerator().mine_trigger_probes(_skill_dir(tmp_path), tp)
    assert len(probes) == 1
    p = probes[0]
    assert p.source == "trace-mined"
    assert p.expect_trigger is False
    assert p.prompt == "帮我把崩溃日志的根因找出来"
    assert "log domain" in p.rationale
    # 注意力安全 a:LLM 只看到 description,skill 正文不进过滤 prompt
    assert len(prompts) == 1
    assert "secret instructions" not in prompts[0]
    assert "analyzes error logs" in prompts[0]


