"""trace-mined trigger 负例测试(spec ②:事实层窗口判定 + 语义层注意力安全过滤)。

事实层(零 LLM):per-query 窗口判定(query 之后到下一条 query 之间无本 skill 的
Skill 调用 → 未触发)+ query 卫生(过短/slash 命令/点名本 skill 跳过)。
语义层:LLM 过滤领域相邻(near_miss 收 / unrelated 丢 / unverified 收人审);
注意力安全 = 只喂 description、分批 ≤10、每条独立结构化 verdict。
"""

import json
from pathlib import Path

from sift.evals.trigger_mining import (
    MINED_QUERY_MIN_CHARS,
    NEAR_MISS_BATCH,
    filter_near_miss,
    mine_untriggered_queries,
    probe_dedup_key,
)
from sift.execution.options import ExecutionOptions


def _skill(name="my-skill", description=("analyzes error logs and reports root causes")):
    return name, description


def _user(q: str) -> str:
    return json.dumps({"type": "user", "message": {"role": "user", "content": q}})


def _skill_call(skill: str) -> str:
    return json.dumps(
        {
            "type": "assistant",
            "message": {
                "role": "assistant",
                "content": [{"type": "tool_use", "name": "Skill", "input": {"skill": skill}}],
            },
        }
    )


def _tool_call(tool: str = "Read") -> str:
    return json.dumps(
        {
            "type": "assistant",
            "message": {
                "role": "assistant",
                "content": [{"type": "tool_use", "name": tool, "input": {"file_path": "/x"}}],
            },
        }
    )


def _write(tmp_path, lines, name="t.jsonl"):
    p = tmp_path / name
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return p


